CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    location_lat DOUBLE PRECISION,
    location_lng DOUBLE PRECISION,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT
);

CREATE UNIQUE INDEX uq_locations_name ON locations (name);

COMMENT ON TABLE locations IS
    'Physical sites that hold stock: outlets (store) and warehouses. kind selects the site role; kind-specific rules live in the application.';

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand TEXT NOT NULL,
    model TEXT NOT NULL,
    manufacturer TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT
);

CREATE UNIQUE INDEX uq_products_brand_model_manufacturer
    ON products (brand, model, manufacturer);

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_product_variants_product
        FOREIGN KEY (product_id) REFERENCES products (id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_product_variants_product_id_name
    ON product_variants (product_id, name);

CREATE TABLE product_variant_selections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_variant_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_product_variant_selections_variant
        FOREIGN KEY (product_variant_id) REFERENCES product_variants (id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_product_variant_selections_product_variant_id_name
    ON product_variant_selections (product_variant_id, name);

CREATE TABLE product_skus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    selection_key TEXT NOT NULL DEFAULT '',
    code TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_product_skus_product
        FOREIGN KEY (product_id) REFERENCES products (id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);

-- deterministic identity: rebuilding the catalog keeps unchanged SKUs
CREATE UNIQUE INDEX uq_product_skus_product_id_selection_key
    ON product_skus (product_id, selection_key);
CREATE UNIQUE INDEX uq_product_skus_product_id_code
    ON product_skus (product_id, code);

COMMENT ON COLUMN product_skus.selection_key IS
    'Sorted selection identifiers joined by "-"; empty when the product has no variants. Rebuilding after a variant change keeps unchanged SKUs and deletes only removed combinations.';
COMMENT ON COLUMN product_skus.code IS
    'Optional immutable business identifier for labels, barcodes, or imports. A value, never a join key.';

CREATE TABLE product_sku_selections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id BIGINT NOT NULL,
    variant_selection_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_product_sku_selections_sku
        FOREIGN KEY (sku_id) REFERENCES product_skus (id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_product_sku_selections_selection
        FOREIGN KEY (variant_selection_id) REFERENCES product_variant_selections (id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_product_sku_selections_sku_id_variant_selection_id
    ON product_sku_selections (sku_id, variant_selection_id);
CREATE INDEX idx_product_sku_selections_variant_selection_id
    ON product_sku_selections (variant_selection_id);

COMMENT ON TABLE product_sku_selections IS
    'Binds one variant selection to a SKU. A SKU carries exactly one selection per variant; the application enforces that rule.';

CREATE TABLE prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id BIGINT NOT NULL,
    location_id BIGINT,
    currency TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_prices_sku
        FOREIGN KEY (sku_id) REFERENCES product_skus (id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_prices_location
        FOREIGN KEY (location_id) REFERENCES locations (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- NULL location_id is the global price; a plain unique index would allow duplicates.
CREATE UNIQUE INDEX uq_prices_global
    ON prices (sku_id, currency) WHERE location_id IS NULL;
CREATE UNIQUE INDEX uq_prices_location
    ON prices (sku_id, currency, location_id) WHERE location_id IS NOT NULL;

COMMENT ON TABLE prices IS
    'The price of a SKU in one currency. NULL location_id is the global price; a set location_id overrides it for that site. Lookups always fall back to the global row. There is no price history; a price is overwritten in place.';

CREATE TABLE inventories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    stock BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_inventories_location
        FOREIGN KEY (location_id) REFERENCES locations (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_inventories_sku
        FOREIGN KEY (sku_id) REFERENCES product_skus (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_inventories_location_id_sku_id
    ON inventories (location_id, sku_id);
CREATE INDEX idx_inventories_sku_id ON inventories (sku_id);

COMMENT ON TABLE inventories IS
    'Current stock of one SKU at one location. A stocked SKU cannot be deleted because sku_id is restricted; the application must zero or transfer stock first.';

CREATE TABLE api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    redacted TEXT NOT NULL,
    hashed_key TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_api_keys_user
        FOREIGN KEY (user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_api_keys_user_id_name ON api_keys (user_id, name);
CREATE UNIQUE INDEX uq_api_keys_hashed_key ON api_keys (hashed_key);

COMMENT ON TABLE api_keys IS
    'Long-lived credentials for one user. A key carries the user current role, so a role change applies on the next validation. Only the SHA-256 digest is stored; the raw key is shown once at creation or rotation.';

COMMENT ON COLUMN api_keys.hashed_key IS
    'SHA-256 hex digest used for lookup and cache keys; never exposed by APIs.';

COMMENT ON COLUMN api_keys.redacted IS
    'Safe display preview of the key, such as pas-a1b2...f9e0.';

COMMENT ON COLUMN api_keys.is_active IS
    'Disabled keys are rejected during validation without being deleted.';

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT
);

CREATE UNIQUE INDEX uq_roles_slug ON roles (slug);
-- At most one default role.
CREATE UNIQUE INDEX uq_roles_is_default ON roles (is_default) WHERE is_default = TRUE;

COMMENT ON TABLE roles IS
    'Role identities. slug is the stable identifier; at most one role may be the default.';

CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uq_permissions_slug ON permissions (slug);

COMMENT ON TABLE permissions IS
    'Stable authorization actions referenced by role grants. Permissions are created, never updated or removed.';

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    name TEXT NOT NULL,
    bio TEXT NOT NULL DEFAULT '',
    avatar_path TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    suspended_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id) REFERENCES roles (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX idx_users_role_id ON users (role_id);

COMMENT ON TABLE users IS
    'Application identities, independent of authentication method. Every user has exactly one role.';

COMMENT ON COLUMN users.avatar_path IS
    'Optional object-storage key for the profile photo; NULL when unset. Never a URL or credentials.';

COMMENT ON COLUMN users.suspended_until IS
    'End of the current suspension; NULL when the account is not suspended. A suspension does not deactivate the account.';

CREATE TABLE role_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by BIGINT,

    CONSTRAINT fk_role_permission_role
        FOREIGN KEY (role_id) REFERENCES roles (id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_role_permission_permission
        FOREIGN KEY (permission_id) REFERENCES permissions (id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_role_permission_role_id_permission_id
    ON role_permission (role_id, permission_id);
CREATE INDEX idx_role_permission_permission_id ON role_permission (permission_id);

COMMENT ON TABLE role_permission IS
    'Grants one permission to one role; the role/permission pair is unique and immutable once created.';

CREATE TABLE base_auths (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    is_email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    is_phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT fk_base_auths_user
        FOREIGN KEY (user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE UNIQUE INDEX uq_base_auths_user_id ON base_auths (user_id);
CREATE UNIQUE INDEX uq_base_auths_username ON base_auths (username);
CREATE UNIQUE INDEX uq_base_auths_email ON base_auths (email);
CREATE UNIQUE INDEX uq_base_auths_phone ON base_auths (phone);

COMMENT ON TABLE base_auths IS
    'Username/password credentials for exactly one user. Email and phone are optional; unique indexes still permit multiple NULL values.';

COMMENT ON COLUMN base_auths.password_hash IS
    'Encoded salted password hash; never plaintext and never returned by APIs.';
